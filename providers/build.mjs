// Builds bundle/nuvio-bundle.js (runtime + every vendored provider) and the
// generated provider lists used by the desktop and iOS apps.
//
//   node build.mjs            rebuild from vendor/
//   node build.mjs --sync     pull the latest providers from GitHub first
//   node build.mjs --sync=PATH  copy from a local checkout instead
import { execFileSync } from 'node:child_process'
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'
import * as esbuild from 'esbuild'

const ROOT = dirname(fileURLToPath(import.meta.url))
const REPO = 'https://github.com/yoruix/nuvio-providers'
const RAW_BASE = 'https://raw.githubusercontent.com/yoruix/nuvio-providers/main/'
const VENDOR = join(ROOT, 'vendor')
const DIST = join(ROOT, 'bundle')
const DESKTOP_LIST = resolve(ROOT, '../desktop/src/shared/nuvioProviders.ts')
const IOS_LIST = resolve(ROOT, '../ios/VixScr/VixScr/Models/NuvioProviders.swift')

// Names that would clash (case-insensitively) with servers the apps keep.
const RENAME = { vixsrc: 'Vixsrc (Nuvio)' }

function sync(arg) {
  let src = typeof arg === 'string' ? resolve(arg) : null
  let tmp = null
  if (!src) {
    tmp = mkdtempSync(join(tmpdir(), 'nuvio-'))
    execFileSync('git', ['clone', '--depth', '1', '--branch', 'main', REPO, tmp], { stdio: 'inherit' })
    src = tmp
  }
  const manifest = JSON.parse(readFileSync(join(src, 'manifest.json'), 'utf8'))
  rmSync(join(VENDOR, 'providers'), { recursive: true, force: true })
  mkdirSync(join(VENDOR, 'providers'), { recursive: true })
  for (const s of manifest.scrapers) cpSync(join(src, s.filename), join(VENDOR, s.filename))
  cpSync(join(src, 'manifest.json'), join(VENDOR, 'manifest.json'))
  cpSync(join(src, 'LICENSE'), join(VENDOR, 'LICENSE'))
  let commit = ''
  try { commit = execFileSync('git', ['-C', src, 'rev-parse', 'HEAD']).toString().trim() } catch { /* not a checkout */ }
  writeFileSync(join(VENDOR, 'SOURCE.txt'), `${REPO}\n${commit}\nsynced ${new Date().toISOString()}\n`)
  if (tmp) rmSync(tmp, { recursive: true, force: true })
  console.log(`Synced ${manifest.scrapers.length} providers`)
}

async function runtime() {
  const out = await esbuild.build({
    entryPoints: [join(ROOT, 'runtime/index.js')],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'es2020',
    minify: true,
    legalComments: 'none',
    // crypto-js probes for node's crypto; the runtime has none.
    alias: { crypto: join(ROOT, 'runtime/empty.js') },
    define: { 'process.env.NODE_ENV': '"production"' },
    logLevel: 'warning'
  })
  return out.outputFiles[0].text
}

function providerList(manifest) {
  return manifest.scrapers.map(s => ({
    id: s.id,
    name: RENAME[s.id] ?? s.name,
    file: s.filename.split('/').pop(),
    base: RAW_BASE + s.filename,
    types: s.supportedTypes ?? ['movie', 'tv'],
    languages: s.contentLanguage ?? [],
    enabled: s.enabled !== false
  }))
}

async function build() {
  const manifest = JSON.parse(readFileSync(join(VENDOR, 'manifest.json'), 'utf8'))
  const list = providerList(manifest)
  const parts = [`/* Vela provider bundle. Generated by providers/build.mjs - do not edit. */`, await runtime()]
  for (const p of list) {
    const src = readFileSync(join(VENDOR, 'providers', p.file), 'utf8')
    const wrapped = `__velaNuvio.register(${JSON.stringify(p.id)}, function (module, exports, require, global, process) {\n${src}\n});`
    new vm.Script(wrapped, { filename: p.file }) // syntax check
    parts.push(wrapped)
  }
  mkdirSync(DIST, { recursive: true })
  writeFileSync(join(DIST, 'nuvio-bundle.js'), parts.join('\n'))

  const header = 'Generated by providers/build.mjs from the vendored Nuvio manifest - do not edit.'
  writeFileSync(DESKTOP_LIST, `// ${header}
export interface NuvioProvider { id: string; name: string; file: string; base: string; types: string[]; languages: string[] }

export const NUVIO_PROVIDERS: NuvioProvider[] = ${JSON.stringify(list.map(({ enabled, ...p }) => p), null, 2)}
`)
  const swiftStr = s => JSON.stringify(s)
  writeFileSync(IOS_LIST, `// ${header}
import Foundation

struct NuvioProvider: Hashable, Sendable {
    let id: String
    let name: String
    let file: String
    let base: String
    let types: [String]
}

enum NuvioProviders {
    static let all: [NuvioProvider] = [
${list.map(p => `        NuvioProvider(id: ${swiftStr(p.id)}, name: ${swiftStr(p.name)}, file: ${swiftStr(p.file)}, base: ${swiftStr(p.base)}, types: [${p.types.map(swiftStr).join(', ')}]),`).join('\n')}
    ]
}
`)
  const kb = Math.round(Buffer.byteLength(parts.join('\n')) / 1024)
  console.log(`Built bundle/nuvio-bundle.js (${list.length} providers, ${kb} KB)`)
}

const syncArg = process.argv.find(a => a === '--sync' || a.startsWith('--sync='))
if (syncArg) sync(syncArg.includes('=') ? syncArg.split('=')[1] : true)
if (!existsSync(join(VENDOR, 'manifest.json'))) throw new Error('vendor/manifest.json missing - run with --sync')
await build()
